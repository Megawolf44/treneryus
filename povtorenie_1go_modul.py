# 4. Как работает сортировка внутри? (Алгоритмы: до мелочей)

"""
Python не показывает "внутренности" (использует TimSort — быстрый, O(n log n)), но давай разберём простые алгоритмы, чтобы ты понял принцип. Это как "ручная сортировка" — мы напишем код сами.
Алгоритм 1: Bubble Sort (Пузырьковая сортировка) — самый простой, но медленный
Аналогия: Пузырьки в воде всплывают вверх. Мы проходим по списку, сравниваем соседей и меняем местами, если не в порядке. Повторяем, пока не отсортировано.
Код:
"""
numbers = [5, 1, 4, 2, 8]

n = len(numbers)  # длина = 5
for i in range(n):  # внешний цикл: n раз
    for j in range(0, n-i-1):  # внутренний: сравниваем соседей
        if numbers[j] > numbers[j+1]:  # если левый > правого — поменять
            numbers[j], numbers[j+1] = numbers[j+1], numbers[j]  # swap (обмен)

print(numbers)  # Вывод: [1, 2, 4, 5, 8]
""" 
По шагам для [5,1,4,2,8] (мелкие детали):

Первый проход (i=0): j=0: 5>1? Да, swap → [1,5,4,2,8]
j=1: 5>4? Да → [1,4,5,2,8]
j=2: 5>2? Да → [1,4,2,5,8]
j=3: 5>8? Нет.
(Самый большой 8 "всплыл" в конец)
Второй проход (i=1): сравниваем до n-1=4, и так далее.
"""