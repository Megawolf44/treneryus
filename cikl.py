# Цикл while

# Цикл while используется для выполнения блока кода до тех пор, пока условие остается истинным.
# Синтаксис: while условие:
# Пример использования цикла while
i = 0 # Инициализация счетчика
while i < 5: # Условие цикла
    print(i)  # Выводит числа от 0 до 4
    i += 1  # Увеличиваем счетчик на 1  

